const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { EventEmitter } = require('node:events');
const { WhatsAppDirectory } = require('../whatsapp-directory');

test('only saved names are displayed, including renamed contacts and LID conversations', async (t) => {
  const storage = fs.mkdtempSync(path.join(os.tmpdir(), 'bot-wap-names-'));
  process.env.STORAGE_DIR = storage;
  delete process.env.DATABASE_URL;
  delete process.env.DATABASE_PRIVATE_URL;
  const db = require('../db');
  const store = require('../store');
  await db.ready;
  t.after(async () => { await db.close(); fs.rmSync(storage, { recursive: true, force: true }); });
  const number = '551199998888';
  const lid = '123456789012345';
  await db.run('INSERT INTO contacts(number,name,push_name) VALUES (?,?,?)', [number, 'Nome corrompido antigo', 'Meu perfil']);
  await store.addMessage(lid, 'client', 'Historico preservado', 'Nome corrompido antigo');
  assert.deepEqual(await store.getContacts(), []);
  assert.equal((await store.getConversation(lid)).name, '');
  const socket = { ev: new EventEmitter() };
  const directory = new WhatsAppDirectory({ socket, store, emit: () => {} });
  const savedName = 'Cliente João (Trabalho)';
  socket.ev.emit('contacts.upsert', [{ id: `${number}@s.whatsapp.net`, lid: `${lid}@lid`, name: savedName }]);
  await directory.queue;
  assert.equal((await store.getContact(number)).name, savedName);
  assert.equal((await store.getConversation(number)).name, savedName);
  assert.equal((await store.getConversation(number)).messages.length, 1);
  socket.ev.emit('contacts.update', [{ id: `${number}@s.whatsapp.net`, notify: 'Perfil diferente', verifiedName: 'Empresa' }]);
  socket.ev.emit('messaging-history.set', { chats: [{ id: `${number}@s.whatsapp.net`, displayName: 'Outro perfil' }] });
  await directory.queue;
  await store.saveContact({ number, name: 'Remetente', pushName: 'Remetente', jid: `${number}@s.whatsapp.net` });
  assert.equal((await store.getAll())[lid].name, savedName);
  socket.ev.emit('contacts.update', [{ id: `${number}@s.whatsapp.net`, name: 'João renomeado' }]);
  await directory.queue;
  assert.equal((await store.getConversation(lid)).name, 'João renomeado');
  socket.ev.emit('contacts.update', [{ id: `${number}@s.whatsapp.net`, name: '' }]);
  await directory.queue;
  assert.deepEqual(await store.getContacts(), []);
  assert.equal((await store.getConversation(lid)).name, '');
  assert.equal((await store.getConversation(lid)).messages.length, 1);
  assert.equal((await store.getConversation(lid)).phoneNumber, number);
  assert.equal((await store.getAll())[lid].phoneNumber, number);
  assert.ok(await store.getKnownJid(lid));
  const oldLid = '987654321012345', oldPhone = '5511977771234';
  await store.addMessage(oldLid, 'client', 'Conversa antiga');
  await store.saveContact({ number: oldPhone, jid: `${oldLid}@lid` });
  assert.equal((await store.getConversation(oldLid)).phoneNumber, oldPhone);
  assert.equal((await store.getAll())[oldLid].phoneNumber, oldPhone);
  assert.deepEqual(await store.getContacts(), []);
  const directoryOnly = '5511966660001', directoryLid = '111111111111111';
  socket.ev.emit('contacts.upsert', [{ id: `${directoryOnly}@s.whatsapp.net`, lid: `${directoryLid}@lid`, name: 'Somente agenda' }]);
  await directory.queue;
  assert.equal((await store.getContact(directoryOnly)).name, 'Somente agenda');
  assert.equal(await store.getConversation(directoryOnly, false), null);
  assert.equal(await store.getConversation(directoryLid, false), null);
  await store.addMessage(directoryLid, 'admin', 'Primeiro envio pelo celular');
  assert.equal((await store.getConversation(directoryOnly, false)).name, 'Somente agenda');
  const canonical = await store.registerConversationAliases(directoryOnly, directoryOnly);
  await store.addMessage(canonical, 'client', 'Resposta pelo telefone');
  assert.equal((await store.getConversation(directoryOnly, false)).messages.length, 2);
  // Legacy empty rows remain stored for metadata, but never enter the inbox.
  await store.getConversation('5511966660002');
  await store.addMessage('5511966660003', 'admin', 'Conversa real');
  await store.addMessage('5511966660004', 'client', '', '', { type: 'audio', mediaUrl: '/audio.ogg' });
  const inbox = await store.getAll();
  assert.equal(inbox['5511966660002'], undefined);
  assert.equal(inbox[directoryOnly], undefined);
  assert.equal(inbox[directoryLid].messages.length, 2, 'phone and LID use the same conversation after starting from agenda metadata');
  assert.ok(inbox['5511966660003']);
  assert.ok(inbox['5511966660004'], 'media-only messages count as an active conversation');
  await store.clearConversation('5511966660003');
  assert.equal((await store.getAll())['5511966660003'], undefined);
});
